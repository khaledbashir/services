#!/usr/bin/env node
/**
 * Generates lib/ai/skills/index.generated.ts — the static import manifest the
 * Next.js bundler needs in order to include every skill in the server build.
 *
 * Why: registry.ts used to keep a hand-written import list plus a runtime
 * `fs.readdirSync` fallback "for dev". The fallback never worked in a built
 * app (no .ts sources ship, and require() can't load TypeScript), so any skill
 * whose file existed but whose import line was forgotten simply did not exist
 * in production. Three of them — assign_designer, search_design_requests,
 * update_design — had been dead that way.
 *
 * This script is the single source of truth, and `npm run build` regenerates
 * it before compiling. `npm run ai:check-skills` fails if it is stale, so a
 * forgotten skill breaks the build instead of vanishing silently.
 *
 * Convention: a skill file is any .ts in lib/ai/skills/ not starting with "_".
 * It must `export default` a Skill. It may also `export const skills` for an
 * array of extra sibling skills.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const skillsDir = path.join(root, 'lib', 'ai', 'skills')
const outFile = path.join(skillsDir, 'index.generated.ts')

const files = fs
  .readdirSync(skillsDir)
  .filter(f => f.endsWith('.ts') && !f.startsWith('_') && f !== 'index.generated.ts')
  .sort()

const modules = files.map(f => {
  const slug = f.replace(/\.ts$/, '')
  const ident = slug.replace(/[^a-zA-Z0-9]/g, '_')
  const source = fs.readFileSync(path.join(skillsDir, f), 'utf8')
  const hasDefault = /export\s+default\s/.test(source)
  const hasSkillsArray = /export\s+const\s+skills\s*[:=]/.test(source)
  if (!hasDefault && !hasSkillsArray) return null
  return { slug, ident, hasDefault, hasSkillsArray }
}).filter(Boolean)

const imports = modules
  .map(m => {
    const parts = []
    if (m.hasDefault) parts.push(`default as ${m.ident}`)
    if (m.hasSkillsArray) parts.push(`skills as ${m.ident}_skills`)
    return `import { ${parts.join(', ')} } from '@/lib/ai/skills/${m.slug}'`
  })
  .join('\n')

const entries = modules
  .flatMap(m => [m.hasDefault ? `  ${m.ident},` : null, m.hasSkillsArray ? `  ...${m.ident}_skills,` : null])
  .filter(Boolean)
  .join('\n')

const banner = `// AUTO-GENERATED by scripts/generate-ai-skill-manifest.mjs — DO NOT EDIT.
// Run \`npm run ai:sync-skills\` after adding or removing a skill file.
// \`npm run build\` regenerates this automatically.
`

const contents = `${banner}
import type { Skill } from '@/lib/ai/types'
${imports}

/** Every skill defined by a file in lib/ai/skills/. */
export const fileSkills: Skill[] = [
${entries}
]

/** Filenames this manifest was generated from — used by the staleness check. */
export const manifestFiles: string[] = [
${modules.map(m => `  '${m.slug}',`).join('\n')}
]
`

const check = process.argv.includes('--check')
const existing = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : ''

if (check) {
  if (existing !== contents) {
    console.error('✗ lib/ai/skills/index.generated.ts is stale.')
    console.error('  A skill file was added or removed without regenerating the manifest.')
    console.error('  Run: npm run ai:sync-skills')
    process.exit(1)
  }
  console.log(`✓ AI skill manifest up to date (${modules.length} skill modules)`)
  process.exit(0)
}

if (existing !== contents) {
  fs.writeFileSync(outFile, contents)
  console.log(`✓ Wrote lib/ai/skills/index.generated.ts (${modules.length} skill modules)`)
} else {
  console.log(`✓ AI skill manifest already current (${modules.length} skill modules)`)
}
